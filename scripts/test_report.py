"""Rebuild the test evidence document from a real verbose Django test run."""

import os
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parent.parent


if __name__ == "__main__":
    command = [sys.executable, "manage.py", "test", "-v", "2"]
    result = subprocess.run(command, cwd=ROOT, env={**os.environ, "PYTHONUNBUFFERED": "1"},
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    match = re.search(r"Ran (\d+) tests in ([\d.]+)s", result.stdout)
    count, seconds = match.groups() if match else ("unknown", "unknown")
    summary = f"{count} tests passed in {seconds} seconds" if result.returncode == 0 else "Test run failed"
    text = (
        "# Virasat test report\n\n"
        "Generated by `python scripts/test_report.py` using `python manage.py test -v 2`.\n\n"
        f"**{summary}.** Django uses a separate test database. Expected permission-denial, "
        "invalid-form, mocked AI timeout and transaction-rollback logs are not failed tests.\n\n"
        "The suite covers models, forms, role and ownership boundaries, CSRF, sessions, "
        "stock, atomic checkout, AI parsing and fallback, requests, proposals, reviews, "
        "wishlist, PWA routes, dash guards, generated imagery and UI presentation regressions.\n\n"
        "## Full command output\n\n```text\n" + result.stdout + "\n```\n"
    )
    (ROOT / "docs/test_report.md").write_text(text, encoding="utf-8")
    print(summary)
    raise SystemExit(result.returncode)
